/**
 * ボクセルの粒度（1 ボクセルの大きさ）のデザインルール。
 *
 * このゲームの見た目は「大きめのブロックを積んだ質感」が前提で、
 * 被弾でブロックが崩れ落ちる部位破壊の演出も、1 個 1 個のブロックが見える大きさでないと映えない。
 * 細かいボクセルで滑らかな彫刻を作ると、従来のユニットと並んだときに浮くうえ、崩壊の破片も粉のようになる。
 * そのため、ユニットのボクセルモデルは次の下限を守る（tests/voxelScale.test.ts が全兵種を検査する）。
 *
 * - テンプレートのボクセル寸法（makeTemplate / Sculpt.spec に渡す値）は VOXEL_SIZE_MIN 以上。
 *   大きいユニットは scale で拡大されるので、ボクセルも一緒に大きくなるのが正しい
 *   （巨人・使徒などの従来モデルと同じ考え方）。大きいからといって細かく刻まない。
 * - 画面上の寸法（テンプレートの寸法 × ユニットの scale）は WORLD_VOXEL_SIZE_MIN 以上。
 *   小さいユニットは、ボクセルを細かくするのではなく、ボクセルの数を減らして小ささを出す。
 * - 目安は兵士と同じ VOXEL_SIZE_STANDARD 前後。細部はボクセルを細かくせず、色分け（塗り）で描く。
 */

/** 標準的な兵士の 1 ボクセルの寸法（頭 0.036〜手足 0.05） */
export const VOXEL_SIZE_STANDARD = 0.04;

/** テンプレートの 1 ボクセルの寸法の下限（scale を掛ける前） */
export const VOXEL_SIZE_MIN = 0.034;

/** 画面上の 1 ボクセルの寸法の下限（テンプレートの寸法 × ユニットの scale） */
export const WORLD_VOXEL_SIZE_MIN = 0.03;
